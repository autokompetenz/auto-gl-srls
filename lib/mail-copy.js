export function mailText(locale, key, vars = {}) {
  const dictionary = copy[normalizeMailLocale(locale)] ?? copy.it
  let value = dictionary[key] ?? copy.it[key] ?? key
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement ?? ''))
  }
  return value
}

export function mailStatus(locale, status) {
  const dictionary = copy[normalizeMailLocale(locale)] ?? copy.it
  return dictionary.statuses[status] ?? copy.it.statuses[status] ?? status
}

export function mailPurchase(locale, value) {
  const dictionary = copy[normalizeMailLocale(locale)] ?? copy.it
  return dictionary.purchases[value] ?? copy.it.purchases[value] ?? value
}

export function mailDelivery(locale, value) {
  const dictionary = copy[normalizeMailLocale(locale)] ?? copy.it
  return dictionary.deliveries[value] ?? copy.it.deliveries[value] ?? value
}

export function mailIntl(locale) {
  return (copy[normalizeMailLocale(locale)] ?? copy.it).intl
}
